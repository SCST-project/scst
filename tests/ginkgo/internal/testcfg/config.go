package testcfg

import (
	"encoding/json"
	"fmt"
	"io"
	"net"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"time"
)

// Config describes one local, disposable SCST host. There are no implicit
// per-user overrides: the named file completely determines a run.
type Config struct {
	AdminCommand           []string `json:"admin_command"`
	DisposableHost         bool     `json:"disposable_host"`
	NamePrefix             string   `json:"name_prefix"`
	ReportDir              string   `json:"report_dir"`
	LockFile               string   `json:"lock_file"`
	CommandTimeout         string   `json:"command_timeout"`
	CleanupTimeout         string   `json:"cleanup_timeout"`
	SettleTimeout          string   `json:"settle_timeout"`
	PollInterval           string   `json:"poll_interval"`
	SuiteTimeout           string   `json:"suite_timeout"`
	BuildTimeout           string   `json:"build_timeout"`
	BuildJobs              int      `json:"build_jobs"`
	BackingDir             string   `json:"backing_dir"`
	FileioThinProvisioning bool     `json:"fileio_thin_provisioning"`
	StressIterations       int      `json:"stress_iterations"`
	ScaleLUNs              int      `json:"scale_luns"`
	IO                     IO       `json:"io"`
	ISCSI                  *ISCSI   `json:"iscsi,omitempty"`
}

// IO configures bounded data verification. BlockDevice is an explicit,
// destructive-test input on the target, never an initiator device path.
type IO struct {
	BlockDevice string `json:"block_device"`
	RegionMB    int    `json:"region_mb"`
	Timeout     string `json:"timeout"`
}

// ISCSI selects a local TCP target and a separate SSH initiator. Credentials
// for test CHAP accounts are generated by the suite, never supplied here.
type ISCSI struct {
	TargetAddress string    `json:"target_address"`
	Port          int       `json:"port"`
	LoginTimeout  string    `json:"login_timeout"`
	Initiator     Initiator `json:"initiator"`
}

type Initiator struct {
	Host           string `json:"host"`
	User           string `json:"user"`
	Port           int    `json:"port"`
	IdentityFile   string `json:"identity_file"`
	LockFile       string `json:"lock_file"`
	DisposableHost bool   `json:"disposable_host"`
}

func Load(path string) (Config, error) {
	c := Config{
		AdminCommand: []string{"scstadmin"}, NamePrefix: "scsttest",
		ReportDir: "results", LockFile: "/tmp/scst-ginkgo.lock",
		CommandTimeout: "30s", CleanupTimeout: "2m", SettleTimeout: "10s",
		PollInterval: "100ms", SuiteTimeout: "15m",
		BuildTimeout: "10m", BuildJobs: 2,
		IO:               IO{RegionMB: 64, Timeout: "3m"},
		StressIterations: 8, ScaleLUNs: 256, FileioThinProvisioning: true,
	}
	f, err := os.Open(path)
	if err != nil {
		return c, err
	}
	defer f.Close()
	d := json.NewDecoder(f)
	d.DisallowUnknownFields()
	decoded := &c
	if err := d.Decode(&decoded); err != nil {
		return c, fmt.Errorf("test configuration: %w", err)
	}
	if decoded == nil {
		return c, fmt.Errorf("test configuration must be a JSON object")
	}
	if err := d.Decode(new(any)); err != io.EOF {
		return c, fmt.Errorf("test configuration must contain exactly one JSON object")
	}
	if err := c.Validate(); err != nil {
		return c, err
	}
	base, err := filepath.Abs(filepath.Dir(path))
	if err != nil {
		return c, err
	}
	for _, p := range []*string{&c.ReportDir, &c.LockFile} {
		if !filepath.IsAbs(*p) {
			*p = filepath.Join(base, *p)
		}
	}
	if c.BackingDir != "" && !filepath.IsAbs(c.BackingDir) {
		c.BackingDir = filepath.Join(base, c.BackingDir)
	}
	if strings.ContainsRune(c.AdminCommand[0], '/') && !filepath.IsAbs(c.AdminCommand[0]) {
		c.AdminCommand[0] = filepath.Join(base, c.AdminCommand[0])
	}
	if c.ISCSI != nil && c.ISCSI.Initiator.IdentityFile != "" && !filepath.IsAbs(c.ISCSI.Initiator.IdentityFile) {
		c.ISCSI.Initiator.IdentityFile = filepath.Join(base, c.ISCSI.Initiator.IdentityFile)
	}
	return c, nil
}

func (c Config) Validate() error {
	if len(c.AdminCommand) == 0 {
		return fmt.Errorf("admin_command must contain an executable")
	}
	for _, arg := range c.AdminCommand {
		if strings.TrimSpace(arg) == "" || strings.ContainsRune(arg, '\x00') {
			return fmt.Errorf("admin_command contains an empty or invalid argument")
		}
	}
	if !regexp.MustCompile(`^[a-z][a-z0-9_]{0,15}$`).MatchString(c.NamePrefix) {
		return fmt.Errorf("name_prefix must contain 1-16 lowercase letters, digits or underscores and start with a letter")
	}
	if c.ReportDir == "" || c.LockFile == "" {
		return fmt.Errorf("report_dir and lock_file must be nonempty")
	}
	for name, value := range map[string]string{
		"command_timeout": c.CommandTimeout, "cleanup_timeout": c.CleanupTimeout,
		"settle_timeout": c.SettleTimeout, "poll_interval": c.PollInterval,
		"suite_timeout": c.SuiteTimeout,
		"build_timeout": c.BuildTimeout,
	} {
		v, err := time.ParseDuration(value)
		if err != nil || v <= 0 {
			return fmt.Errorf("%s must be a positive Go duration", name)
		}
	}
	if Duration(c.PollInterval) > Duration(c.SettleTimeout) {
		return fmt.Errorf("poll_interval exceeds settle_timeout")
	}
	if c.BuildJobs < 1 {
		return fmt.Errorf("build_jobs must be positive")
	}
	if c.StressIterations < 1 || c.StressIterations > 1000 {
		return fmt.Errorf("stress_iterations must be between 1 and 1000")
	}
	if c.ScaleLUNs < 2 || c.ScaleLUNs > 2048 {
		return fmt.Errorf("scale_luns must be between 2 and 2048")
	}
	if c.IO.RegionMB < 1 || c.IO.RegionMB > 1024 {
		return fmt.Errorf("io.region_mb must be between 1 and 1024")
	}
	if d, err := time.ParseDuration(c.IO.Timeout); err != nil || d <= 0 || d > time.Hour {
		return fmt.Errorf("io.timeout must be positive and at most 1h")
	}
	if p := c.IO.BlockDevice; p != "" && (!strings.HasPrefix(p, "/dev/") || filepath.Clean(p) != p || strings.ContainsAny(p, " \t\r\n,;\"{}\\\x00")) {
		return fmt.Errorf("io.block_device must be a clean absolute /dev path without attribute delimiters")
	}
	if c.ISCSI != nil {
		i := c.ISCSI
		if Duration(c.CommandTimeout) > time.Hour {
			return fmt.Errorf("iSCSI command_timeout must not exceed 1h")
		}
		ip := net.ParseIP(i.TargetAddress)
		if ip == nil || ip.To4() == nil || strings.Contains(i.TargetAddress, ":") || ip.IsUnspecified() || ip.IsLoopback() || ip.IsMulticast() {
			return fmt.Errorf("iscsi.target_address must be a unicast, non-loopback IPv4 address")
		}
		if i.Port < 1 || i.Port > 65535 || i.Initiator.Port < 1 || i.Initiator.Port > 65535 {
			return fmt.Errorf("iSCSI and SSH ports must be between 1 and 65535")
		}
		if !regexp.MustCompile(`^[a-zA-Z0-9][a-zA-Z0-9._-]*$`).MatchString(i.Initiator.Host) || i.Initiator.User != "root" {
			return fmt.Errorf("iscsi.initiator requires a host name or IPv4 address and user root")
		}
		if !filepath.IsAbs(i.Initiator.LockFile) || strings.ContainsRune(i.Initiator.LockFile+i.Initiator.IdentityFile, '\x00') {
			return fmt.Errorf("initiator lock_file must be absolute and SSH paths must not contain NUL")
		}
		d, err := time.ParseDuration(i.LoginTimeout)
		if err != nil || d < time.Second || d%time.Second != 0 || d >= Duration(c.CommandTimeout) {
			return fmt.Errorf("iscsi.login_timeout must be whole seconds, positive and below command_timeout")
		}
	}
	return nil
}

// Duration is used only after Validate has checked all duration fields.
func Duration(s string) time.Duration {
	d, _ := time.ParseDuration(s)
	return d
}
